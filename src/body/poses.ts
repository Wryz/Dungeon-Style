export type PoseName = keyof typeof POSE_SPECS;

const cache = new Map<PoseName, Pose>();

export function getPose(name: PoseName): Pose {
  let p = cache.get(name);
  if (!p) {
    p = resolvePose(POSE_SPECS[name]);
    cache.set(name, p);
  }
  return p;
}

export function resolveSpec(spec: PoseSpec, out?: Pose): Pose {
  return resolvePose(spec, out);
}
